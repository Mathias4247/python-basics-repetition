def average_of_two_numbers(a, b):
    return (a + b) / 2


def rectangle_area(w, h):
    return w * h


def fahrenheit_to_celsius(f):
    return (f - 32) * 5 / 9


def celsius_to_fahrenheit(c):
    return c * 9 / 5 + 32


def echo(text):
    return text[:3] * 3


